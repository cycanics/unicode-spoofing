#!/usr/bin/env python3
"""
Regenerates src/data/html-entities.generated.ts: the HTML5 named character
references (WHATWG list, as shipped in Python's html.entities.html5): every name
with its semicolon, and the legacy names the HTML tokenizer also reads without it.

    python3 scripts/generate-html-entities.py
"""
import html.entities
from pathlib import Path

rows = []
for name, value in sorted(html.entities.html5.items()):
    if not name.endswith(';'):
        continue
    cps = ','.join('%x' % ord(c) for c in value)
    rows.append('%s=%s' % (name[:-1], cps))
packed = ';'.join(rows)
legacy = sorted(n for n in html.entities.html5 if not n.endswith(';'))
out = Path(__file__).resolve().parent.parent / 'src' / 'data' / 'html-entities.generated.ts'
out.write_text(
    '// Generated by scripts/generate-html-entities.py. Do not edit.\n'
    '// Data: the named character references of the HTML Living Standard (WHATWG,\n'
    '// https://html.spec.whatwg.org/multipage/named-characters.html), (c) WHATWG\n'
    '// (Apple, Google, Mozilla, Microsoft), licensed under CC BY 4.0\n'
    '// (https://creativecommons.org/licenses/by/4.0/); taken from Python\'s html.entities.\n'
    '// %d names with a semicolon: name=hex code points, `;`-separated.\n'
    "export const HTML_NAMED_PACKED =\n  '%s';\n"
    '// The %d legacy names the HTML tokenizer also reads without a semicolon.\n'
    "export const HTML_LEGACY_NAMES = '%s';\n" % (len(rows), packed, len(legacy), ' '.join(legacy))
)
print('wrote', len(rows), 'names to', out)
