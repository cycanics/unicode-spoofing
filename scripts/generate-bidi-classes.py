#!/usr/bin/env python3
"""
Regenerates src/data/bidi-classes.generated.ts: the Bidi_Class of every code
point (UCD, as shipped in Python's unicodedata), as runs. Unassigned code points
take the defaults of DerivedBidiClass.txt (R, AL and ET blocks; L elsewhere).

    python3 scripts/generate-bidi-classes.py
"""
import unicodedata
from pathlib import Path

# The classes src/bidi.ts reads; every other class (B, S, WS, BN, the explicit
# embedding, override and isolate controls) reads as ON within a word.
KEEP = ['L', 'R', 'AL', 'EN', 'AN', 'ES', 'ET', 'CS', 'NSM', 'ON']

# DerivedBidiClass.txt @missing defaults for unassigned code points (UCD 15.0).
DEFAULTS = [
    (0x0590, 0x05FF, 'R'), (0x0600, 0x07BF, 'AL'), (0x07C0, 0x085F, 'R'),
    (0x0860, 0x08FF, 'AL'), (0x20A0, 0x20CF, 'ET'), (0xFB1D, 0xFB4F, 'R'),
    (0xFB50, 0xFDCF, 'AL'), (0xFDF0, 0xFDFF, 'AL'), (0xFE70, 0xFEFF, 'AL'),
    (0x10800, 0x10CFF, 'R'), (0x10D00, 0x10D3F, 'AL'), (0x10D40, 0x10EBF, 'R'),
    (0x10EC0, 0x10EFF, 'AL'), (0x10F00, 0x10F2F, 'R'), (0x10F30, 0x10F6F, 'AL'),
    (0x10F70, 0x10FFF, 'R'), (0x1E800, 0x1EC6F, 'R'), (0x1EC70, 0x1ECBF, 'AL'),
    (0x1ECC0, 0x1ECFF, 'R'), (0x1ED00, 0x1ED4F, 'AL'), (0x1ED50, 0x1EDFF, 'R'),
    (0x1EE00, 0x1EEFF, 'AL'), (0x1EF00, 0x1EFFF, 'R'),
]


def bidi(cp):
    c = unicodedata.bidirectional(chr(cp))
    if c == '':
        c = next((k for a, b, k in DEFAULTS if a <= cp <= b), 'L')
    return c if c in KEEP else 'ON'


runs = []
prev = None
for cp in range(0x110000):
    k = bidi(cp)
    if k != prev:
        runs.append('%x:%d' % (cp, KEEP.index(k)))
        prev = k
out = Path(__file__).resolve().parent.parent / 'src' / 'data' / 'bidi-classes.generated.ts'
out.write_text(
    '// Generated by scripts/generate-bidi-classes.py. Do not edit.\n'
    '// Data: Bidi_Class from the Unicode Character Database %s (Python unicodedata),\n'
    '// (c) Unicode, Inc., under the Unicode License v3 (https://www.unicode.org/license.txt);\n'
    '// unassigned code points per DerivedBidiClass.txt. Classes: %s (others read ON).\n'
    '// %d runs: hex start:class index, `;`-separated.\n'
    "export const BIDI_CLASS_RUNS =\n  '%s';\n"
    % (unicodedata.unidata_version, ' '.join(KEEP), len(runs), ';'.join(runs))
)
print(len(runs), 'runs')
