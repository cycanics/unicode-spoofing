#!/usr/bin/env node
/**
 * Regenerates src/data/ivd.generated.ts from the Ideographic Variation
 * Database: per base, the supplement selectors (U+E0100–E01EF) registered for
 * it. A selector not registered for its base selects no glyph and is a payload
 * channel (docs/confusion-model.md §15.5).
 *
 *   node scripts/generate-ivd.mjs                       # fetch the latest IVD_Sequences.txt
 *   node scripts/generate-ivd.mjs --file path/to/IVD_Sequences.txt
 *
 * Packed form: per base, the code point delta to the previous base and a bit
 * mask of its selectors (bit k = U+E0100 + k), both base 36, ',' between entries.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const file = args[args.indexOf('--file') + 1];
const source = args.includes('--file')
  ? readFileSync(file, 'utf8')
  : await (await fetch('https://www.unicode.org/ivd/data/latest/IVD_Sequences.txt')).text();

const version = /^#\s+(\d{4}-\d{2}-\d{2})/m.exec(source)?.[1] ?? 'unknown';
const bases = new Map();
let entries = 0;
for (const line of source.split('\n')) {
  const m = /^([0-9A-F]{4,6}) ([0-9A-F]{5});/.exec(line);
  if (!m) continue;
  entries++;
  const base = parseInt(m[1], 16);
  const k = parseInt(m[2], 16) - 0xe0100;
  if (k < 0 || k > 0xef) throw new Error(`selector out of range: ${line}`);
  if (k > 52) throw new Error(`selector beyond the packed mask (53 bits): ${line}`);
  (bases.get(base) ?? bases.set(base, new Set()).get(base)).add(k);
}
const sorted = [...bases.keys()].sort((a, b) => a - b);
let prev = 0;
const packed = sorted
  .map((b) => {
    const mask = [...bases.get(b)].reduce((m, k) => m + 2 ** k, 0);
    const s = `${(b - prev).toString(36)}:${mask.toString(36)}`;
    prev = b;
    return s;
  })
  .join(',');
const maxSel = Math.max(...[...bases.values()].flatMap((ks) => [...ks]));
const out = `// Generated by scripts/generate-ivd.mjs from IVD_Sequences.txt ${version}. Do not edit.
// ${entries} entries, ${sorted.length} bases, selectors up to U+${(0xe0100 + maxSel).toString(16).toUpperCase()}.

export const IVD_VERSION = '${version}';

export const IVD_PACKED =
  '${packed}';
`;
const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'data',
  'ivd.generated.ts',
);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(
  `${target}: ${sorted.length} bases, ${entries} entries, IVD ${version}, ${out.length} bytes`,
);
