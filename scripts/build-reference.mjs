#!/usr/bin/env node
/**
 * Vendors a git revision of `src/` as one ESM bundle for the parity and
 * performance tests (test/fixtures/reference/main.mjs): the behaviour the
 * streaming core is compared with.
 *
 *   node scripts/build-reference.mjs [rev=d26b10b]
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rev = process.argv[2] ?? 'd26b10b';
const esbuild = createRequire(
  join(realpathSync(join(root, 'node_modules', 'tsup')), 'package.json'),
)('esbuild');
const dir = mkdtempSync(join(tmpdir(), 'unicode-spoofing-ref-'));
try {
  const files = execFileSync('git', ['ls-tree', '-r', '--name-only', rev, 'src'], {
    cwd: root,
    encoding: 'utf8',
  })
    .split('\n')
    .filter(Boolean);
  for (const f of files) {
    mkdirSync(dirname(join(dir, f)), { recursive: true });
    writeFileSync(join(dir, f), execFileSync('git', ['show', `${rev}:${f}`], { cwd: root }));
  }
  const out = join(root, 'test', 'fixtures', 'reference', 'main.mjs');
  esbuild.buildSync({
    entryPoints: [join(dir, 'src', 'index.ts')],
    bundle: true,
    format: 'esm',
    minify: true,
    platform: 'neutral',
    banner: { js: `// unicode-spoofing src at ${rev}, generated by scripts/build-reference.mjs` },
    outfile: out,
  });
  console.log(`${out} ← ${rev}`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
